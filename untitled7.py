class ThompsonSampling(Bandit):
    def __init__(self, p):
        self.p = p
        self.k = len(p)
        self.mu_prior = np.zeros(self.k)
        self.tau_prior = np.zeros(self.k)
        self.history = {'Bandit': [], 'Reward': [], 'Algorithm': [], 'Regret': []}

    def __repr__(self):
        return f"ThompsonSampling(p={self.p})"

    def pull(self):
        samples = []
        for i in range(self.k):
            if self.tau_prior[i] == 0:
                sampled_val = np.random.normal(0, 10)
            else:
                sampled_val = np.random.normal(self.mu_prior[i], 1.0 / np.sqrt(self.tau_prior[i]))
            samples.append(sampled_val)
        return np.argmax(samples)

    def update(self, arm, reward):
        old_tau = self.tau_prior[arm]
        old_mu = self.mu_prior[arm]
        new_tau = old_tau + KNOWN_PRECISION
        new_mu = (old_tau * old_mu + KNOWN_PRECISION * reward) / new_tau
        self.tau_prior[arm] = new_tau
        self.mu_prior[arm] = new_mu

    def experiment(self, num_trials=NUMBER_OF_TRIALS):
        optimal_reward = max(self.p)
        for _ in range(num_trials):
            arm = self.pull()
            reward = np.random.normal(self.p[arm], 1.0 / np.sqrt(KNOWN_PRECISION))
            self.update(arm, reward)
            regret = optimal_reward - self.p[arm]

            self.history['Bandit'].append(arm)
            self.history['Reward'].append(reward)
            self.history['Algorithm'].append('ThompsonSampling')
            self.history['Regret'].append(regret)
        return pd.DataFrame(self.history)

    def report(self):
        df = pd.DataFrame(self.history)
        df[['Bandit', 'Reward', 'Algorithm']].to_csv('thompson_sampling_results.csv', index=False)
        avg_reward = df['Reward'].mean()
        avg_regret = df['Regret'].mean()
        logger.info(f"[ThompsonSampling] Average Reward per trial: {avg_reward:.4f} | Cumulative: {df['Reward'].sum():.2f}")
        logger.info(f"[ThompsonSampling] Average Regret per trial: {avg_regret:.4f} | Cumulative: {df['Regret'].sum():.2f}")


def comparison():
    logger.info("Initializing and running Epsilon-Greedy experiment...")
    eg = EpsilonGreedy(BANDIT_REWARD)
    eg_df = eg.experiment()
