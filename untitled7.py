class EpsilonGreedy(Bandit):
    def __init__(self, p):
        self.p = p
        self.k = len(p)
        self.counts = np.zeros(self.k)
        self.values = np.zeros(self.k)
        self.t = 0
        self.history = {'Bandit': [], 'Reward': [], 'Algorithm': [], 'Regret': []}

    def __repr__(self):
        return f"EpsilonGreedy(p={self.p})"

    def pull(self):
        self.t += 1
        epsilon = 1.0 / self.t
        if np.random.random() < epsilon:
            return np.random.choice(self.k)
        return np.argmax(self.values)

    def update(self, arm, reward):
        self.counts[arm] += 1
        self.values[arm] += (reward - self.values[arm]) / self.counts[arm]

    def experiment(self, num_trials=NUMBER_OF_TRIALS):
        optimal_reward = max(self.p)
        for _ in range(num_trials):
            arm = self.pull()
            reward = np.random.normal(self.p[arm], 1.0 / np.sqrt(KNOWN_PRECISION))
            self.update(arm, reward)
            regret = optimal_reward - self.p[arm]

            self.history['Bandit'].append(arm)
            self.history['Reward'].append(reward)
            self.history['Algorithm'].append('EpsilonGreedy')
            self.history['Regret'].append(regret)
        return pd.DataFrame(self.history)

    def report(self):
        df = pd.DataFrame(self.history)
        df[['Bandit', 'Reward', 'Algorithm']].to_csv('epsilon_greedy_results.csv', index=False)
        avg_reward = df['Reward'].mean()
        avg_regret = df['Regret'].mean()
        logger.info(f"[EpsilonGreedy] Average Reward per trial: {avg_reward:.4f} | Cumulative: {df['Reward'].sum():.2f}")
        logger.info(f"[EpsilonGreedy] Average Regret per trial: {avg_regret:.4f} | Cumulative: {df['Regret'].sum():.2f}")

